// 1. Ép sang Số (Number)
let strPrice = "1500";
console.log(Number(strPrice)); // 1500 (Trở thành số)
console.log(parseInt("10.5px")); // 10 (Lấy phần nguyên, bỏ chữ)
console.log(parseFloat("10.5px")); // 10.5 (Lấy cả phần thập phân)

// 2. Ép sang Chuỗi (String)
let age = 25;
console.log(String(age)); // "25"
console.log(age.toString()); // "25"

// 3. Ép sang Boolean (Logic Đúng/Sai)
console.log(Boolean(1)); // true
console.log(Boolean(0)); // false

console.log("5" + 2)
console.log("5" - 2)
console.log(1 + 2 + "3")

console.log("5" * 3)
console.log("5" / 2)

